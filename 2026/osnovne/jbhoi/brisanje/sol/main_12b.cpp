#include <iostream>
using namespace std;

// Rjesenje za podzadatak 1: svi brojevi su stepeni dvojke
// Najmanji stepen generise sve vece (npr. 2+2=4, 2+2+2+2=8)
// Odgovor je uvijek N-1
int main() {
    int n;
    cin >> n;
    // Procitaj brojeve (nepotrebno za odgovor)
    for (int i = 0; i < n; i++) {
        int x;
        cin >> x;
    }
    cout << n - 1 << endl;
    return 0;
}
